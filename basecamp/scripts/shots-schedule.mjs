import { chromium } from 'playwright-core';
import { mkdirSync } from 'node:fs';
const OUT = process.env.OUT ?? './shots';
mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(`pageerror: ${e.message}`));
page.on('console', (m) => { if (m.type() === 'error') errors.push(`console: ${m.text()}`); });
await page.goto('http://localhost:4173/');
await page.click('text=Set up camp');
await page.waitForSelector('text=Rings');
await page.click('text=Change today');
await page.waitForTimeout(300);
await page.screenshot({ path: `${OUT}/s1-today-change.png` });
await page.click('text=Upper C');
await page.waitForTimeout(300);
await page.screenshot({ path: `${OUT}/s2-today-upperc.png` });
await page.click('a[aria-label="Profile"]');
await page.click('text=Weekly schedule');
await page.waitForTimeout(300);
await page.selectOption('select[aria-label="Wed workout"]', 'lowerC');
await page.screenshot({ path: `${OUT}/s3-schedule.png` });
await page.click('text=Save');
await page.click('a[aria-label="Plan"]');
await page.waitForTimeout(300);
await page.screenshot({ path: `${OUT}/s4-plan.png` });
console.log(errors.length ? errors.join('\n') : 'no errors');
await browser.close();
